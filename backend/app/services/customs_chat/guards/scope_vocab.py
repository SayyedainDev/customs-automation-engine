#: Overrides both signals: requests for something this assistant does not
#: do, even when trade vocabulary is present ("write a python parser for
#: invoices"). A customs word co-occurring here is exactly the pattern that
#: previously bypassed the guard ("for customs purposes, who won the FIFA
#: World Cup 2026?") - it now forces the LLM classifier (Stage B) rather than
#: an automatic accept.
OUT_OF_DOMAIN_INTENT: tuple[str, ...] = (
    r"\bwrite\b[^.?!]*\b(code|function|script|program|poem|song|story|essay|joke)\b",
    r"\b(python|javascript|typescript|java|c\+\+|golang|rust|sql query|regex)\b",
    r"\b(football|cricket|soccer|basketball|tennis|match result|score|world cup|fifa|olympics)\b",
    r"\b(movie|movies|film|films|netflix|song|lyrics|album|celebrity)\b",
    r"\b(recipe|cook|cooking|restaurant)\b",
    r"\b(repair|fix)\b[^.?!]*\b(phone|laptop|car|bike|tv|computer)\b",
    r"\b(love poem|dating|horoscope|astrology)\b",
    r"\bsort(ing)?\b[^.?!]{0,20}\b(function|algorithm|array|list)\b",
    r"\b(election|president|prime minister|parliament vote)\b",
    r"\b(stock market|crypto|bitcoin|invest(ment)?\s+advice)\b",
    r"\b(diagnose|symptoms|medication|prescription)\b",
)

#: Layer 4 (output guard) also uses these: an instruction embedded in a
#: retrieved passage is content to display, never a directive to follow.
#: Ported unchanged from domain_guard.py - this list is well-researched and
#: the failure modes it names are real.
INJECTION_PATTERNS: tuple[str, ...] = (
    r"ignore\s+(all\s+|any\s+|your\s+|the\s+)?(previous\s+|prior\s+|above\s+)?instructions?",
    r"disregard\s+(all\s+|any\s+|the\s+)?(previous\s+|prior\s+|above\s+)?(instructions?|rules?)",
    r"forget\s+(everything|all\s+previous|your\s+instructions)",
    r"you\s+are\s+now\s+",
    r"pretend\s+(you\s+are|to\s+be)",
    r"act\s+as\s+(if|a|an)\s+",
    r"system\s+prompt",
    r"jailbreak",
    r"override\s+(your|the)\s+(instructions?|rules?|settings?)",
    r"new\s+instructions?\s*:",
    r"set\s+(the\s+)?status\s+to\s+",
    r"mark\s+(this\s+)?shipment\s+(as\s+)?(approved|passed|cleared)",
    r"reveal\s+(your|the)\s+(system\s+)?prompt",
    r"what\s+(are|is)\s+your\s+(instructions|system\s+prompt|rules)",
)

#: An eight-digit tariff code, written plainly or as 6203.4200.
TARIFF_CODE = re.compile(r"\b\d{4}[.\s-]?\d{4}\b")

